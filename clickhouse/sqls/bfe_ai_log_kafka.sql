    `ai_apikeytags`           JSON COMMENT 'API Key 标签 JSON 对象，仅用于打平求值',
    `ai_requested_model`      String,
    `ai_target_model`         String,
    `ai_stream`               UInt8,
    `ai_input_tokens`         Int64,
    `ai_output_tokens`        Int64,
    `ai_total_tokens`         Int64,
    `ai_cache_read_tokens`    Int64,
    `ai_cache_write_tokens`   Int64,
    `ai_audio_input_tokens`   Int64,
    `ai_audio_output_tokens`  Int64,
    `ai_image_count`          Int64,
    `ai_ttft_us`              Int64,
