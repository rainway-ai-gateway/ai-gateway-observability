-- ============================================================
-- Kafka 引擎暂存表：schema 与 mod_kafka 输出的 JSON 消息同构（80 字段）
-- 设计依据：clickhouse/docs/modifications/2026-10-01-clickhouse-dock/design-changes.md
-- ============================================================
-- 机制说明（等价 Doris Routine Load 的 Kafka 消费端）：
--   * 本表只做消息暂存，不落盘存储（Kafka 引擎表无实际数据）；
--   * 消费 MV（bfe_ai_log_load_mv）从本表读取消息，完成 JSON 打平与 UTC 换算后
--     写入明细表 bfe_ai_request_log；
--   * input_format_skip_unknown_fields = 1：PB/log-reader 新增字段先于本表 DDL
--     到达时被跳过而不是报错，保证消费不中断；
--   * ai_apikeytags 为 JSON 对象，以 ClickHouse JSON 类型承载，仅在 MV 内
--     经 JSONExtractString 打平（level1~level5 十列），源对象不落明细表；
--   * kafka_group_name 必须与 Doris / StarRocks 链路的消费组不同（位点独立）。
-- ============================================================
CREATE TABLE IF NOT EXISTS ${CLICKHOUSE_DATABASE}.bfe_ai_log_kafka
